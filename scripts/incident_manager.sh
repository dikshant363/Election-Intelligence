#!/usr/bin/env bash
# Election Intelligence Platform — Autopilot Deduplicated Incident Manager
# Creates or updates GitHub issues with deduplication, triage classification, and secret sanitization

set -euo pipefail

TITLE=""
SEVERITY="P2-Medium"
LOG_FILE=""
RUN_URL="${GITHUB_SERVER_URL:-https://github.com}/${GITHUB_REPOSITORY:-dikshant363/Election-Intelligence}/actions/runs/${GITHUB_RUN_ID:-0}"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --title)
            TITLE="$2"
            shift 2
            ;;
        --severity)
            SEVERITY="$2"
            shift 2
            ;;
        --log-file)
            LOG_FILE="$2"
            shift 2
            ;;
        --run-url)
            RUN_URL="$2"
            shift 2
            ;;
        *)
            echo "Unknown argument: $1" >&2
            exit 1
            ;;
    esac
done

if [ -z "${TITLE}" ]; then
    echo "ERROR: --title is required." >&2
    exit 1
fi

# Sanitize logs to ensure zero credentials or tokens leak
sanitize_content() {
    local text="$1"
    # Redact postgres credentials
    text=$(echo "${text}" | sed -E 's|postgres(ql)?://[^:]+:[^@]+@|postgres://[REDACTED_USER]:[REDACTED_SECRET]@|g')
    # Redact Bearer tokens
    text=$(echo "${text}" | sed -E 's|Bearer [a-zA-Z0-9_\-\.]{8,}|Bearer [REDACTED_SECRET]|gI')
    # Redact API keys and secrets
    text=$(echo "${text}" | sed -E 's|(api[_-]?key|secret|password|token)[ =:]["'\'']?[a-zA-Z0-9_\-\.]{8,}["'\'']?|\1=[REDACTED_SECRET]|gI')
    echo "${text}"
}

RAW_LOGS="No diagnostic log provided."
if [ -n "${LOG_FILE}" ] && [ -f "${LOG_FILE}" ]; then
    RAW_LOGS="$(cat "${LOG_FILE}" | tail -n 50)"
fi
SANITIZED_LOGS="$(sanitize_content "${RAW_LOGS}")"

ISSUE_TITLE="[Autopilot Incident]: ${TITLE}"
TIMESTAMP="$(date -u +"%Y-%m-%d %H:%M:%SZ")"

echo "=========================================================="
echo "  Election Intelligence Platform — Incident Management"
echo "=========================================================="
echo "Incident Title: ${ISSUE_TITLE}"
echo "Severity:       ${SEVERITY}"
echo "Workflow Run:   ${RUN_URL}"
echo "Timestamp:      ${TIMESTAMP}"
echo "----------------------------------------------------------"

if ! command -v gh >/dev/null 2>&1; then
    echo "WARNING: 'gh' CLI tool is not installed or not in PATH."
    echo "Diagnostic summary:"
    echo "${SANITIZED_LOGS}"
    exit 0
fi

# Check if GitHub token or credentials are available
if ! gh auth status >/dev/null 2>&1; then
    echo "WARNING: 'gh' CLI is not authenticated. Skipping remote issue creation."
    exit 0
fi

echo "==> Searching existing open issues for deduplication..."
EXISTING_ISSUE=$(gh issue list --state open --label "autopilot-incident" --json number,title --jq ".[] | select(.title | contains(\"${TITLE}\")) | .number" | head -n 1 || echo "")

if [ -n "${EXISTING_ISSUE}" ]; then
    echo "==> Found existing open incident #${EXISTING_ISSUE}. Appending diagnostic update (Preventing duplicate issue)..."
    COMMENT_BODY=$(cat <<EOF
### 🔄 Autopilot Incident Re-occurrence Update
**Timestamp:** \`${TIMESTAMP}\`
**Severity:** \`${SEVERITY}\`
**Workflow Run:** [View Workflow Run](${RUN_URL})

**Latest Diagnostic Log (Sanitized):**
\`\`\`text
${SANITIZED_LOGS}
\`\`\`

*This update was automatically generated by the Free Autopilot Health Monitor.*
EOF
)
    gh issue comment "${EXISTING_ISSUE}" --body "${COMMENT_BODY}"
    echo "==> Successfully updated issue #${EXISTING_ISSUE}."
else
    echo "==> No existing issue found. Creating new deduplicated incident..."
    ISSUE_BODY=$(cat <<EOF
## 🚨 Autopilot Health Incident Report

### Overview
- **Incident:** ${TITLE}
- **Severity:** \`${SEVERITY}\`
- **Initial Detection:** \`${TIMESTAMP}\`
- **Workflow Run:** [View Failure Logs](${RUN_URL})

### System State & Invariants
- **Platform:** Election Intelligence Platform (Pure Rust Full-Stack)
- **Budget Compliance:** ₹0/month Free-Tier Enforced (No paid resources touched)
- **Neutrality & Civic Mission:** Unaffected (Audits and historical data immutable)

### Diagnostic Evidence (Sanitized)
\`\`\`text
${SANITIZED_LOGS}
\`\`\`

### Recommended Remediation Playbook
1. Inspect deployment readiness via \`./scripts/health_check.sh\`.
2. Review container logs on Render / local host.
3. Verify Neon Serverless PostgreSQL compute state and connection string.
4. If code defect, trigger bounded self-repair via \`.github/workflows/autopilot-repair.yml\`.

---
*Created automatically by Election Intelligence Platform Autopilot Governance System.*
EOF
)
    gh issue create \
        --title "${ISSUE_TITLE}" \
        --label "autopilot-incident,bug,${SEVERITY}" \
        --body "${ISSUE_BODY}"
    echo "==> New incident issue created."
fi
echo "=========================================================="
